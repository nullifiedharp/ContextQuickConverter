"""Writes installer/menus.iss: the [Registry] entries for every right-click menu.

Generated from quickconvert/formats.py so the installer always matches the app
(add a format or preset there and the next build.bat picks it up). Each menu is
an installer checkbox (task); unticking one on a later re-run removes it.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from quickconvert.shell_integration import SFA, UNINSTALL_KEY, _menus, plan_registry  # noqa: E402

EXE = r"{app}\QuickConvert.exe"
TASK = {"QuickConvert": "menu_convert", "QuickConvertResize": "menu_resize",
        "QuickConvertCompress": "menu_compress"}


def q(text: str) -> str:
    """Quote a value for an Inno Setup parameter (embedded " doubled). Braces are
    left alone on purpose so {app} expands; no menu label contains a brace."""
    assert "{" not in text.replace("{app}", ""), f"unexpected brace in {text!r}"
    return '"' + text.replace('"', '""') + '"'


def main() -> Path:
    out = ["; GENERATED by tools/make_installer_menus.py - do not edit by hand.", "",
           "[Registry]",
           "; Remove the Settings > Apps entry left by the old in-app \"Install\" button (v1.0/1.1).",
           f"Root: HKCU; Subkey: {q(UNINSTALL_KEY)}; ValueType: none; Flags: deletekey"]
    for verb, title, exts, _ in _menus():
        task = TASK[verb]
        out += ["", f"; ---- {title} ----"]
        for ext in exts:
            base = rf"{SFA}\.{ext}\shell\{verb}"
            # If the box is unticked on a re-run, take the old menu away.
            out.append(f"Root: HKA; Subkey: {q(base)}; ValueType: none; "
                       f"Flags: deletekey uninsdeletekey; Tasks: not {task}")
            # All-users install: clear a per-user copy from the old in-app installer
            # so the menu doesn't show up twice.
            out.append(f"Root: HKCU; Subkey: {q(base)}; ValueType: none; Flags: deletekey; "
                       "Check: IsAdminInstallMode")
        first = set()
        for key, name, value in plan_registry(prefix=f'"{EXE}"', icon=f"{EXE},0", verbs=[verb]):
            flags = ""
            if key.endswith(rf"\shell\{verb}") and key not in first:
                first.add(key)
                # deletekey first clears presets from an older version.
                flags = "; Flags: deletekey uninsdeletekey"
            out.append(f"Root: HKA; Subkey: {q(key)}; ValueType: string; "
                       f"ValueName: {q(name)}; ValueData: {q(value)}{flags}; Tasks: {task}")
    path = ROOT / "installer" / "menus.iss"
    path.write_text("\r\n".join(out) + "\r\n", encoding="utf-8-sig")
    return path


if __name__ == "__main__":
    p = main()
    print(f"wrote {p.relative_to(ROOT)} ({p.read_text(encoding='utf-8-sig').count(chr(10))} lines)")
